def seed_data():
    print("🚀 Отправка тестовых документов в микросервис...")
    created_ids = []

    for doc in SAMPLE_DOCUMENTS:
        req = urllib.request.Request(
            f"{BASE_URL}/documents/",
            data=json.dumps(doc).encode("utf-8"),
            headers={"Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(req) as resp:
                res = json.loads(resp.read().decode("utf-8"))
                created_ids.append(res["id"])
                print(f"  [+] Документ создан: ID {res['id']} ({res['source']})")
        except Exception as e:
            print(f"  [-] Ошибка при создании документа {doc['source']}: {e}")

    print("\n⏳ Ожидание асинхронной индексации воркером (AsyncIOScheduler)...")
    time.sleep(6)

    print("\n📊 Статус индексации документов:")
    for doc_id in created_ids:
        try:
            with urllib.request.urlopen(f"{BASE_URL}/documents/{doc_id}") as resp:
                res = json.loads(resp.read().decode("utf-8"))
                print(f"  • ID {res['id']} [{res['source']}]: {res['status']}")
        except Exception as e:
            print(f"  • ID {doc_id}: Ошибка получения статуса ({e})")

    print("\n✅ Загрузка завершена! Теперь можно делать запросы на POST /ask.")


if __name__ == "__main__":
    seed_data()
